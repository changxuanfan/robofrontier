"""Bounded recovery for a measured open hand resting on supported cargo.

The Relay dispatcher calls this controller directly. Motion uses Trial.execute;
planning writes scratch FK data, never live cargo poses, physics or monitor state.
"""
from pathlib import Path
import hashlib
import math

import mujoco
import numpy as np

from robofrontier.robot_control import rotation_vector


def target_contact_allowed(distance, initial_depth=None):
    """Allow separation from an existing compliant contact, not deeper contact.

    Positive distances are clearance, including proximity pairs generated by
    the screen model's margin. They are not a new physical collision.
    """
    limit=-.0001 if initial_depth is None else initial_depth-.0001
    return distance>=limit


def robot_cargo_contact(t, ident, robot):
    owned=set(t.monitor.relay_v2.states[ident]['all_geoms'])
    return any(c.dist<=.0002 and any(int(a) in owned and
        t.model.body(int(t.model.geom_bodyid[int(b)])).name.startswith(robot+'_')
        for a,b in ((c.geom1,c.geom2),(c.geom2,c.geom1))) for c in t.data.contact)


def plan_open_contact_withdrawal(t, ident, robot, joint_rad, goal_names=None, actual_support=None):
    """Read-only short escape with the actual 80 mm opening and fixed cargo."""
    arm=t.arms[robot];observation=arm.observe()
    if arm.job is not None or arm.grasp_force is not None:
        raise ValueError('Contact withdrawal requires resolved force-free execution')
    if observation['gripper_width_m']<t.task['mechanism']['cross_section_m'][0]+.012:
        raise ValueError('Contact withdrawal requires measured open jaws')
    if t.held.get(robot) not in (None,ident):
        raise ValueError('Contact withdrawal belongs to the actual cargo label')
    relay=t.monitor.relay_v2;state=relay.states[ident]
    accepted=None if goal_names is None else set(goal_names(t,ident))
    inside=relay.inside(state) if accepted is None else ident in accepted
    support=set(t.monitor.bilateral(state['rod_geoms'],positive_force=True)
        if actual_support is None else actual_support)-{robot}
    grounded=inside and (relay.environment_contact(state['all_geoms'])
        or ident in relay.supported_payloads(goal_only=True,require_all=False,inside_ids=accepted))
    if len(support)<2 and not grounded:
        raise ValueError('Contact withdrawal requires two actual receivers or grounded Goal cargo')
    if any(robot_cargo_contact(t,name,robot) for name in relay.states if name!=ident):
        raise ValueError('Different cargo contact needs its own owner review')
    goal=np.asarray(joint_rad,dtype=float);start=t.data.qpos[arm.qids].copy()
    if goal.shape!=(7,) or not np.isfinite(goal).all() or np.any(goal<arm.ik.limits[:,0]) or np.any(goal>arm.ik.limits[:,1]):
        raise ValueError('Finite in-limit seven-joint target required')
    old_point=t.data.site_xpos[arm.site].copy();old_rotation=t.data.site_xmat[arm.site].reshape(3,3).copy()
    point,rotation=arm.ik.pose(goal)
    angle_limit=.20 if len(support)>=2 else .04
    if np.linalg.norm(point-old_point)>.06 or np.linalg.norm(rotation_vector(rotation,old_rotation))>angle_limit:
        raise ValueError('Contact escape exceeds its short supported withdrawal scope')
    data=mujoco.MjData(t.screen_model);data.qpos[:]=t.data.qpos;mujoco.mj_forward(t.screen_model,data)
    owned=set(state['all_geoms']);owner=t.monitor.geom_owner;rid=list(t.arms).index(robot);baseline={}
    for c in data.contact:
        a,b=map(int,c.geom);oa,ob=owner[a],owner[b]
        body=(int(t.model.geom_bodyid[a]) if oa==rid and b in owned else
              int(t.model.geom_bodyid[b]) if ob==rid and a in owned else None)
        if body is not None and c.dist<=.0002:baseline[body]=min(float(c.dist),baseline.get(body,0.))
    if not baseline:raise ValueError('Use the existing separated empty-hand controller')
    if min(baseline.values())<-.003:raise ValueError('Initial deep contact needs owner diagnosis')
    count=max(81,math.ceil(float(np.max(abs(goal-start)))/.005)+1);final_contact=False
    for fraction in np.linspace(0,1,count):
        data.qpos[:]=t.data.qpos;data.qpos[arm.qids]=start+(goal-start)*fraction
        mujoco.mj_forward(t.screen_model,data)
        for c in data.contact:
            a,b=map(int,c.geom);oa,ob=owner[a],owner[b]
            if oa!=rid and ob!=rid:continue
            if oa==ob:
                names=[t.model.body(int(t.model.geom_bodyid[g])).name for g in (a,b)]
                if c.dist<-.001 and not all('finger' in name for name in names):
                    raise RuntimeError('Contact withdrawal would self-collide')
                continue
            obj,rg=(b,a) if oa==rid else (a,b);body=int(t.model.geom_bodyid[rg]);name=t.model.body(body).name
            if name==robot+'_link0':continue
            if obj in owned:
                if not target_contact_allowed(float(c.dist),baseline.get(body)):
                    raise RuntimeError('Contact withdrawal would deepen or create cargo penetration')
                if fraction==1 and c.dist<=.0002:final_contact=True
            elif c.dist<.001:
                raise RuntimeError('Contact withdrawal would hit another robot or scene object')
    if final_contact:raise RuntimeError('Fixed-cargo withdrawal endpoint is not separated')
    return dict(joint_start_rad=start.tolist(),joint_target_rad=goal.tolist(),samples=count,
        independent_receivers=sorted(support),grounded_goal=bool(grounded),
        angle_limit_rad=angle_limit,
        initial_contacts={t.model.body(b).name:v for b,v in baseline.items()},
        tcp_start_m=old_point.tolist(),tcp_target_m=point.tolist())


def execute_open_contact_withdrawal(t, ident, robot, joint_rad, goal_names=None):
    plan=plan_open_contact_withdrawal(t,ident,robot,joint_rad,goal_names=goal_names)
    digest=hashlib.sha256(Path(__file__).read_bytes()).hexdigest()
    t.event('engineering_open_contact_withdrawal',payload=ident,robot=robot,
        controller_source_sha256=digest,controller_scope='privileged assisted normal actuators',plan=plan)
    t.execute('recovery-open-contact-withdraw',{robot:('move',dict(
        joint_rad=plan['joint_target_rad'],joint_speed_rad_s=.12))})
    arm=t.arms[robot]
    if arm.job is not None or arm.grasp_force is not None:
        raise RuntimeError('Contact withdrawal feedback is unresolved')
    if any(robot_cargo_contact(t,name,robot) for name in t.monitor.relay_v2.states):
        raise RuntimeError('Open withdrawal moved but cargo contact remains; inspect original feedback')
    # The existing empty-hand controller uses the same post-feedback cache rule.
    t.held.pop(robot,None)
